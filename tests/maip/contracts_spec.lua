local config = require('maip.config')
local client = require('maip.client')
local receipts = require('maip.receipts')
local ui = require('maip.ui')
local utils = require('maip.utils')
local stub = require('luassert.stub')

describe('deployed MAIP contracts', function()
  local displayed, sent
  before_each(function()
    config.setup({api_key='fixture-key', agent_id='maip-agent:fixture', max_retries=3})
    displayed, sent = nil, nil
    stub(ui,'notify'); stub(ui,'error')
    stub(ui,'float',function(_, lines) displayed=table.concat(lines,'\n') end)
    stub(utils,'git_branch',function() return 'qa' end)
    stub(utils,'git_commit_hash_full',function() return 'fixture-commit' end)
  end)
  after_each(function()
    ui.notify:revert(); ui.error:revert(); ui.float:revert()
    utils.git_branch:revert(); utils.git_commit_hash_full:revert()
    if type(client.post)=='table' then client.post:revert() end
    if type(client.get)=='table' then client.get:revert() end
  end)
  it('creates a receipt using the deployed body and labels buffer hashing',function()
    stub(client,'post',function(path,opts) sent={path=path,body=opts.body};opts.on_success({receipt_id='fixture'}) end)
    local buf=vim.api.nvim_create_buf(false,true)
    vim.api.nvim_buf_set_lines(buf,0,-1,false,{'hello','world'})
    receipts.create_for_buffer(buf)
    assert.equals('/agent-receipts',sent.path)
    assert.equals('action',sent.body.receipt_type)
    assert.equals('file_edit',sent.body.action)
    assert.equals(utils.sha256('hello\nworld'),sent.body.metadata.artifact_hash)
    assert.equals('editor_text_utf8_lf_joined',sent.body.metadata.hash_scope)
    assert.is_nil(sent.body.algorithm)
    vim.api.nvim_buf_delete(buf,{force=true})
  end)
  it('does not label unsigned or incomplete responses verified',function()
    stub(client,'get',function(path,opts)
      assert.equals('/agent-receipts/verify/'..vim.uri_encode('maip-receipt:fixture'),path)
      opts.on_success({valid=true,signature_verified=false,verdict='VALID'})
    end)
    local result
    receipts.verify('maip-receipt:fixture',function(data) result=data end)
    assert.is_false(result.valid)
    assert.truthy(displayed:find('INCOMPLETE'))
  end)
  it('preserves an unverifiable verdict',function()
    stub(client,'get',function(_,opts) opts.on_success({valid=false,signature_verified=false,verdict='UNVERIFIABLE'}) end)
    receipts.verify('fixture')
    assert.truthy(displayed:find('UNVERIFIABLE'))
  end)
  it('requires all three cryptographic success fields',function()
    stub(client,'get',function(_,opts) opts.on_success({valid=true,signature_verified=true,verdict='VALID'}) end)
    local result;receipts.verify('fixture',function(data) result=data end)
    assert.is_true(result.valid)
  end)
  it('uses filter endpoint and preserves structured response records',function()
    stub(client,'get',function(path,opts)
      assert.equals('/agent-receipts/filter',path)
      assert.equals('maip-agent:fixture',opts.params.agent_id)
      opts.on_success({data={{receipt_id='r1',action='file_edit',created_at='2026-10-01T00:00:00Z'}}})
    end)
    local result;receipts.list({agent_id='maip-agent:fixture'},function(data) result=data end)
    assert.equals('r1',result[1].receipt_id)
    assert.equals('file_edit',result[1].action_type)
    assert.equals('2026-10-01T00:00:00Z',result[1].timestamp)
  end)
  it('keeps credentials off process arguments and prefers explicit bearer',function()
    local cfg=config.get();cfg.bearer_token='fixture-session'
    local args=table.concat(client._build_curl_args('GET',cfg.api_url..'/agents',nil,cfg),' ')
    assert.is_nil(args:find('fixture%-key'))
    assert.is_nil(args:find('fixture%-session'))
    local auth=client._auth_config(cfg)
    assert.truthy(auth:find('Authorization: Bearer fixture%-session'))
    assert.is_nil(auth:find('X%-API%-Key'))
  end)
  it('rejects injected credential headers and plaintext URLs',function()
    config.setup({api_key='fixture\nheader: injected'});assert.is_false(config.validate())
    config.setup({api_key='fixture',api_url='http://example.com/v1'});assert.is_false(config.validate())
  end)
end)
